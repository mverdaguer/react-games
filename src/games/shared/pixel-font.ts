export function bitmapRects(bitmap: readonly string[]): { x: number; y: number; w: number }[] {
  const rects: { x: number; y: number; w: number }[] = []
  for (let y = 0; y < bitmap.length; y += 1) {
    const row = bitmap[y] ?? ""
    let x = 0
    while (x < row.length) {
      if (row[x] !== "#") {
        x += 1
        continue
      }
      const start = x
      while (x < row.length && row[x] === "#") x += 1
      rects.push({ x: start, y, w: x - start })
    }
  }
  return rects
}

export function glyphRows(char: string): readonly string[] {
  return GLYPHS[char] ?? SPACE
}

export function textWidth(text: string): number {
  if (text.length === 0) return 0
  return text.length * 4 - 1
}
